package main

import (
	"fmt"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"
)

// RawConfig must match internal/config/types.go closely for unmarshaling during generation
type RawConfig struct {
	Version int `yaml:"version"`

	AWS struct {
		SSO struct {
			StartURL  string `yaml:"start_url"`
			Region    string `yaml:"region"`
			AccountID string `yaml:"account_id"`
			RoleName  string `yaml:"role_name"`
		} `yaml:"sso"`
		ProfileName string `yaml:"profile_name"`
		Region      string `yaml:"region"`
	} `yaml:"aws"`

	Artifact struct {
		Domain      string `yaml:"domain"`
		DomainOwner string `yaml:"domain_owner"`
		Repository  string `yaml:"repository"`
		Region      string `yaml:"region"`
	} `yaml:"artifact"`

	Package struct {
		UVIndexName       string `yaml:"uv_index_name"`
		ValidationPackage string `yaml:"validation_package"`
	} `yaml:"package"`

	CLI struct {
		LogLevel       string `yaml:"log_level"`
		NoColor        bool   `yaml:"no_color"`
		NonInteractive bool   `yaml:"non_interactive"`
	} `yaml:"cli"`

	Features struct {
		CodeArtifact bool `yaml:"codeartifact"`
		Docker       bool `yaml:"docker"`
		Java         bool `yaml:"java"`
		Terraform    bool `yaml:"terraform"`
		Kubernetes   bool `yaml:"kubernetes"`
	} `yaml:"features"`
}

func main() {
	yamlPath := filepath.Join("configs", "default.yaml")
	outPath := filepath.Join("internal", "config", "embedded.go")

	data, err := os.ReadFile(yamlPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Failed to read %s: %v\n", yamlPath, err)
		os.Exit(1)
	}

	var raw RawConfig
	if err := yaml.Unmarshal(data, &raw); err != nil {
		fmt.Fprintf(os.Stderr, "Failed to unmarshal YAML: %v\n", err)
		os.Exit(1)
	}

	// Generate Go code
	code := fmt.Sprintf(`// Code generated by scripts/generate_config.go. DO NOT EDIT.
package config

// DefaultConfig is the statically compiled configuration loaded from configs/default.yaml at build time.
var DefaultConfig = &Config{
	Version: %d,
	AWS: AWSConfig{
		SSO: SSOConfig{
			StartURL:  %q,
			Region:    %q,
			AccountID: %q,
			RoleName:  %q,
		},
		ProfileName: %q,
		Region:      %q,
	},
	Artifact: ArtifactConfig{
		Domain:      %q,
		DomainOwner: %q,
		Repository:  %q,
		Region:      %q,
	},
	Package: PackageConfig{
		UVIndexName:       %q,
		ValidationPackage: %q,
	},
	CLI: CLIConfig{
		LogLevel:       %q,
		NoColor:        %t,
		NonInteractive: %t,
	},
	Features: FeaturesConfig{
		CodeArtifact: %t,
		Docker:       %t,
		Java:         %t,
		Terraform:    %t,
		Kubernetes:   %t,
	},
}
`,
		raw.Version,
		raw.AWS.SSO.StartURL, raw.AWS.SSO.Region, raw.AWS.SSO.AccountID, raw.AWS.SSO.RoleName,
		raw.AWS.ProfileName, raw.AWS.Region,
		raw.Artifact.Domain, raw.Artifact.DomainOwner, raw.Artifact.Repository, raw.Artifact.Region,
		raw.Package.UVIndexName, raw.Package.ValidationPackage,
		raw.CLI.LogLevel, raw.CLI.NoColor, raw.CLI.NonInteractive,
		raw.Features.CodeArtifact, raw.Features.Docker, raw.Features.Java, raw.Features.Terraform, raw.Features.Kubernetes,
	)

	if err := os.WriteFile(outPath, []byte(code), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "Failed to write %s: %v\n", outPath, err)
		os.Exit(1)
	}

	fmt.Println("Successfully generated internal/config/embedded.go from configs/default.yaml")
}
